package edu.uva.liftlab.graphchecker.launcher;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.Collections;

/**
 * The Hadoop {@code Configuration} overrides the launcher owns.
 *
 * <p>The workload's own test class builds its {@code Configuration} itself,
 * and the launcher must not edit it: a checked-in test that carries the
 * experiment's settings stops being the upstream workload. The launcher
 * instead renders its overrides into an ordinary Hadoop XML resource with a
 * name of its own and has the workload JVM register it through
 * {@code Configuration.addDefaultResource}.</p>
 *
 * <p>The unique name is load-bearing. Writing an {@code hdfs-site.xml} and
 * putting it first on the classpath would work mechanically but would hide
 * the checkout's own test {@code hdfs-site.xml}, which sets
 * {@code dfs.namenode.fs-limits.min-block-size} to zero - without it the
 * 100-byte block size the balancer test configures is rejected outright. A
 * separately named resource is appended to the default list, so it shadows
 * none of them.</p>
 *
 * <p>Appended <em>later</em> than the site files is what makes it win, and
 * that is a property of when it is registered, not of its name:
 * {@code hdfs-default.xml} and {@code hdfs-site.xml} are registered by
 * {@code HdfsConfiguration}'s static initializer, so anything registered
 * before that class is first touched loses to them. See
 * {@link WorkloadEntryPoint#CONFIG_DEFAULTS_CLASSES_PROPERTY}.</p>
 *
 * <p>Values a test sets programmatically still win over any resource. That is
 * correct: the launcher only needs the keys the workload never assigns.</p>
 */
public final class WorkloadConfiguration {

    /** Resource name the workload JVM registers; not a Hadoop site file. */
    public static final String RESOURCE_NAME =
            "graphchecker-workload-site.xml";

    private final Map<String, String> values;

    private WorkloadConfiguration(Map<String, String> values) {
        this.values = Collections.unmodifiableMap(values);
    }

    public static WorkloadConfiguration of(Map<String, String> values) {
        return new WorkloadConfiguration(values == null
                ? Collections.<String, String>emptyMap() : values);
    }

    public Map<String, String> values() {
        return values;
    }

    public boolean isEmpty() {
        return values.isEmpty();
    }

    /** Renders the overrides as a Hadoop configuration resource. */
    public String toXml() {
        StringBuilder xml = new StringBuilder();
        xml.append("<?xml version=\"1.0\"?>\n");
        xml.append("<!-- Generated by GraphChecker's source-first launcher. ")
                .append("Registered with Configuration.addDefaultResource, ")
                .append("so it overrides the site files without hiding them. ")
                .append("-->\n");
        xml.append("<configuration>\n");
        for (Map.Entry<String, String> entry : values.entrySet()) {
            xml.append("  <property>\n");
            xml.append("    <name>").append(escape(entry.getKey()))
                    .append("</name>\n");
            xml.append("    <value>").append(escape(entry.getValue()))
                    .append("</value>\n");
            xml.append("  </property>\n");
        }
        xml.append("</configuration>\n");
        return xml.toString();
    }

    /**
     * Writes the resource into {@code confDir} and returns that directory,
     * which the caller puts on the workload classpath.
     */
    public Path writeTo(Path confDir) throws LauncherException {
        try {
            Files.createDirectories(confDir);
            Files.write(confDir.resolve(RESOURCE_NAME),
                    toXml().getBytes(StandardCharsets.UTF_8));
        } catch (IOException failure) {
            throw new LauncherException(LauncherDiagnostic.IO_FAILED,
                    "cannot write " + confDir.resolve(RESOURCE_NAME), failure);
        }
        return confDir;
    }

    private static String escape(String value) {
        if (value == null) {
            return "";
        }
        StringBuilder escaped = new StringBuilder(value.length());
        for (int index = 0; index < value.length(); index++) {
            char character = value.charAt(index);
            switch (character) {
                case '&':
                    escaped.append("&amp;");
                    break;
                case '<':
                    escaped.append("&lt;");
                    break;
                case '>':
                    escaped.append("&gt;");
                    break;
                case '"':
                    escaped.append("&quot;");
                    break;
                default:
                    escaped.append(character);
            }
        }
        return escaped.toString();
    }
}
