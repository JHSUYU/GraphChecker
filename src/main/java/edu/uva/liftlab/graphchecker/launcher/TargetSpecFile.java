package edu.uva.liftlab.graphchecker.launcher;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Writes the target specification the existing resolver already reads.
 *
 * <p>The launcher does not introduce a naming mechanism of its own. A target
 * is named exactly twice in this codebase: by
 * {@code @CausynthExceptionTarget("<id>")} on the constructed exception in the
 * analyzed source, and by {@code exception_target_id} in the target
 * specification that {@code CausynthTargetResolver} loads. The launcher's job
 * is to make those two agree - it takes the id as an explicit input, emits the
 * specification, and hands the analysis stage its path through
 * {@code causynth.target.spec}.</p>
 *
 * <p>The specification grammar is intentionally minimal on the reader's side:
 * one unindented {@code key: value} line, comments allowed, and a second key
 * is an error. This writer produces exactly what that reader accepts and
 * rejects an id that could not survive the round trip.</p>
 */
public final class TargetSpecFile {

    /** File name written into the launcher output directory. */
    public static final String FILE_NAME = "target.yaml";

    private TargetSpecFile() {
    }

    /** Renders the one-key specification for {@code exceptionTargetId}. */
    public static String render(String exceptionTargetId)
            throws LauncherException {
        String id = exceptionTargetId == null ? "" : exceptionTargetId.trim();
        if (id.isEmpty()) {
            throw new LauncherException(LauncherDiagnostic.USAGE,
                    "exception target id is blank");
        }
        if (id.indexOf('\n') >= 0 || id.indexOf('\r') >= 0
                || id.indexOf('#') >= 0) {
            throw new LauncherException(LauncherDiagnostic.USAGE,
                    "exception target id is not a single plain token: "
                            + exceptionTargetId);
        }
        return "# Generated by GraphChecker's source-first launcher.\n"
                + "exception_target_id: " + id + "\n";
    }

    /** Writes the specification into {@code outputDir} and returns its path. */
    public static Path write(Path outputDir, String exceptionTargetId)
            throws LauncherException {
        String text = render(exceptionTargetId);
        Path path = outputDir.resolve(FILE_NAME);
        try {
            Files.createDirectories(outputDir);
            Files.write(path, text.getBytes(StandardCharsets.UTF_8));
        } catch (IOException failure) {
            throw new LauncherException(LauncherDiagnostic.IO_FAILED,
                    "cannot write " + path, failure);
        }
        return path;
    }
}
